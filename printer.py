def text_current_game(current_games: dict, chat_id: str) -> str:
    """Возвращает текст, который сообщает все параметры игры.

    Args:
        current_games: Словарь с текущими данными игры.
        chat_id: ID чата пользователя.
    """
    count_players = len(current_games[chat_id]["lst_players"])
    num_shpions = current_games[chat_id]["num_shpions"]
    user_theme = current_games[chat_id]["user_theme"]
    game_mode = current_games[chat_id]["game_mode"]

    if game_mode == 'classic':
        mode_display = "📜 Классика"
        shpions_text = f"*{num_shpions}* 🕵️‍♂️"
        peace_text = f"*{count_players - num_shpions}* 🧑‍🌾"
    else:
        mode_display = "🎲 Хаос"
        shpions_text = "_Случайно_ 🔮"
        peace_text = "_Случайно_ 🔮"

    text = (
        f"""⚙️ *ПОДТВЕРЖДЕНИЕ НАСТРОЕК* ⚙️
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
👥 Всего игроков: *{count_players}*
🌾 Мирных жителей: {peace_text}
🕵️‍♂️ Шпионов в игре: {shpions_text}
📂 Тема раунда: *{user_theme}*
🏆 Выбранный режим: *{mode_display}*
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
🤔 _Вы точно хотите начать игру с этими настройками?_"""
    )
    return text


