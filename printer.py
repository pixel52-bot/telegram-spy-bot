def text_roles(role: str, user_theme: str, secret_word: str = "") -> str:
    """Возвращает текст, отталкиваясь от аргументов, о том, какая у вас роль, тема и секретное слово.

    Args:
        role: Игровая роль.
        user_theme: Игровая тема.
        secret_word: Секретное слово.
    """
    if role == "live":
        text = (
f"""Вы Мирный житель! 🧑‍🌾
Тема игры: {user_theme}
        
Секретное слово: {secret_word}"""
        )
    else:
        text = (
f"""Вы Шпион! 🕵️‍♂️
Тема игры: {user_theme}
        
Постарайтесь узнать секретное слово у мирных!"""
        )
    return text
